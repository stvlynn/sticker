/** Prefix match: longest key whose title starts with it (case-insensitive). */
export function animatedOverride(title) {
  const lowered = title.toLowerCase()
  let best = null
  for (const [key, value] of Object.entries(animatedOverrides)) {
    if (lowered.startsWith(key.toLowerCase()) && (best === null || key.length > best.key.length)) {
      best = { key, value }
    }
  }
  return best?.value ?? null
}
