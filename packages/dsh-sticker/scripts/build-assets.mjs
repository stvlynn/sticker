#!/usr/bin/env node
/**
 * Build the DSH bundle's self-contained rendered assets.
 *
 * Inputs:
 *   packages/sticker-catalog/catalog.json          canonical metadata
 *   packages/sticker-catalog/assets/thumbs.json     pre-encoded 256px WebP stills
 *   public/stickers/animated/*.webm                 original animated media
 *
 * Outputs:
 *   lib/assets/thumbs/*.webp                         256px stills (content-addressed)
 *   lib/assets/anim/*.webm                           240px loops (content-addressed)
 *   lib/catalog.json                                 runtime lookup catalog
 *
 * Budget: total generated bytes must stay under 20 MB. A failed WebM conversion
 * falls back to the still by leaving `video: null` in the runtime catalog.
 */
import { createHash } from 'node:crypto'
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packageDir = resolve(here, '..')
const repo = resolve(packageDir, '../..')
const catalogPath = join(repo, 'packages/sticker-catalog/catalog.json')
const thumbsManifestPath = join(repo, 'packages/sticker-catalog/assets/thumbs.json')
const thumbsSource = join(repo, 'packages/sticker-catalog/assets/thumbs')
const outDir = join(packageDir, 'lib/assets')
const thumbsOut = join(outDir, 'thumbs')
const animOut = join(outDir, 'anim')
const runtimeCatalogPath = join(packageDir, 'lib/catalog.json')
const MAX_TOTAL_BYTES = 20 * 1024 * 1024

const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'))
const thumbsManifest = JSON.parse(readFileSync(thumbsManifestPath, 'utf8'))
const thumbs = thumbsManifest.thumbs ?? {}

const hasFfmpeg = spawnSync('ffmpeg', ['-version'], { stdio: 'ignore' }).status === 0

rmSync(outDir, { recursive: true, force: true })
mkdirSync(thumbsOut, { recursive: true })
mkdirSync(animOut, { recursive: true })

let failures = 0
let videoFailures = 0
const runtime = []

for (const sticker of catalog.stickers) {
  const mapped = thumbs[sticker.id]
  if (mapped === undefined) {
    console.error(`build-assets: no thumbnail for ${sticker.id}`)
    failures++
    continue
  }
  const sourceThumb = join(thumbsSource, mapped.replace(/^thumbs\//u, ''))
  if (!existsSync(sourceThumb)) {
    console.error(`build-assets: missing thumbnail file ${sourceThumb}`)
    failures++
    continue
  }
  const thumbName = mapped.replace(/^thumbs\//u, '')
  copyFileSync(sourceThumb, join(thumbsOut, thumbName))

  let video = null
  if (sticker.type === 'animated' && sticker.video !== null) {
    if (!hasFfmpeg) {
      videoFailures++
    } else {
      const input = join(repo, 'public', sticker.video)
      if (!existsSync(input)) {
        console.error(`build-assets: missing video ${input}`)
        videoFailures++
      } else {
        const tmp = join(animOut, `.${sticker.id}.webm`)
        const result = spawnSync(
          'ffmpeg',
          [
            '-hide_banner',
            '-loglevel',
            'error',
            '-y',
            '-i',
            input,
            '-vf',
            'scale=240:-2:flags=lanczos,fps=15',
            '-c:v',
            'libvpx-vp9',
            '-b:v',
            '0',
            '-crf',
            '42',
            '-an',
            tmp,
          ],
          { encoding: 'utf8' },
        )
        if (result.status !== 0 || !existsSync(tmp)) {
          console.error(`build-assets: ffmpeg failed for ${sticker.id}: ${result.stderr?.trim() ?? ''}`)
          videoFailures++
        } else {
          const bytes = readFileSync(tmp)
          const hash = createHash('sha1').update(bytes).digest('hex').slice(0, 8)
          const fileName = `${sticker.id}-${hash}.webm`
          renameSync(tmp, join(animOut, fileName))
          video = `anim/${fileName}`
        }
      }
    }
  }

  runtime.push({
    id: sticker.id,
    title: sticker.title,
    type: sticker.type,
    tags: sticker.tags,
    moods: sticker.moods,
    whenToUse: sticker.whenToUse,
    image: sticker.image,
    thumb: `thumbs/${thumbName}`,
    video,
  })
}

if (failures > 0) {
  console.error(`build-assets: ${failures} sticker(s) missing stills`)
  process.exit(1)
}
if (runtime.length !== catalog.stickers.length) {
  console.error(`build-assets: expected ${catalog.stickers.length} runtime entries, got ${runtime.length}`)
  process.exit(1)
}
if (hasFfmpeg && videoFailures > 0) {
  console.warn(`build-assets: warning: ${videoFailures} animated sticker(s) fell back to stills`)
}

const totalBytes = totalSize(outDir)
if (totalBytes > MAX_TOTAL_BYTES) {
  console.error(
    `build-assets: generated assets exceed the ${(MAX_TOTAL_BYTES / 1024 / 1024).toFixed(0)} MB budget (${totalBytes} bytes)`,
  )
  process.exit(1)
}

writeFileSync(
  runtimeCatalogPath,
  `${JSON.stringify(
    {
      version: 1,
      generatedAt: new Date().toISOString(),
      packageName: 'dsh-lynn-sticker',
      counts: {
        static: runtime.filter(row => row.type === 'static').length,
        animated: runtime.filter(row => row.type === 'animated').length,
        total: runtime.length,
        withVideo: runtime.filter(row => row.video !== null).length,
      },
      stickers: runtime,
    },
    null,
    2,
  )}\n`,
  'utf8',
)

const animatedWithVideo = runtime.filter(row => row.video !== null).length
console.log(
  `build-assets: wrote ${runtime.length} runtime entries (${animatedWithVideo}/${catalog.counts.animated} animated loops), ${(totalBytes / 1024 / 1024).toFixed(2)} MB total -> lib/catalog.json`,
)

function totalSize(directory) {
  let total = 0
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const full = join(directory, entry.name)
    if (entry.isDirectory()) total += totalSize(full)
    else if (entry.isFile()) total += statSync(full).size
  }
  return total
}
